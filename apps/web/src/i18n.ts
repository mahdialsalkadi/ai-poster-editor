export const messages: Record<Lang, Record<MessageKey, string>> = { ar, en };

export function translate(lang: Lang, key: MessageKey, vars: TranslationVars = {}): string {
  return messages[lang][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

export function translator(lang: Lang): Translator {
  return (key, vars) => translate(lang, key, vars);
}

export type LangStorage = Pick<Storage, 'getItem' | 'setItem'>;

function defaultStorage(): LangStorage | undefined {
  return typeof localStorage === 'undefined' ? undefined : localStorage;
}

export function readStoredLang(storage: LangStorage | undefined = defaultStorage()): Lang {
  const value = storage?.getItem(UI_LANG_KEY);
  return value === 'en' || value === 'ar' ? value : 'ar';
}

export function writeStoredLang(
  lang: Lang,
  storage: LangStorage | undefined = defaultStorage(),
): void {
  storage?.setItem(UI_LANG_KEY, lang);
}

export function applyDocumentLang(
  lang: Lang,
  root: Pick<HTMLElement, 'dir' | 'lang'> = document.documentElement,
): void {
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';
  root.lang = lang;
}

export type I18nValue = {
  lang: Lang;
  dir: Direction;
  t: Translator;
  setLang: (lang: Lang) => void;
};

export const I18nContext = createContext<I18nValue | null>(null);

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nContext.Provider');
  return value;
}
